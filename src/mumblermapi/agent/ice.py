"""murmur-agent's Ice glue: loading Ice, the authenticator Murmur calls and the channels as the reconciler sees them"""

from __future__ import annotations

import logging
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from importlib.resources import files
from types import ModuleType
from typing import Any

from .authenticator import TRY_LATER, UNKNOWN, Authenticator
from .reconcile import ChannelRefused, ExistingChannel

LOGGER = logging.getLogger(__name__)
_SLICE_FALLBACK_DIR = "/usr/share/ice/slice"
# Murmur forwards unchecked logins of up to 8 MiB, each invalid UTF-8 byte re-encoded as three, and drops the
# authenticator when a call fails: anything smaller lets anyone stop every login. The certificate chain comes on top.
MURMUR_MESSAGE_BYTES = 0x7FFFFF
ADAPTER = "Agent"
ADAPTER_MESSAGE_KIB = 3 * MURMUR_MESSAGE_BYTES // 1024 + 1024
# Murmur lists every user or channel in one answer; this holds several hundred users with full comments, though
# nothing in Murmur caps the plugin data a client sends
ICE_MESSAGE_KIB = 10 * 1024


def load_ice() -> tuple[ModuleType, ModuleType]:  # pragma: no cover  # needs the image's Ice
    """Ice, and the MumbleServer module it builds from Murmur's slice"""
    import Ice  # provided by the container image

    slice_dir = Ice.getSliceDir() or _SLICE_FALLBACK_DIR
    Ice.loadSlice("", ["-I" + slice_dir, str(files("mumblermapi") / "MumbleServer.ice")])
    import MumbleServer  # generated by loadSlice above

    return Ice, MumbleServer


def _answer[T](call: Callable[[], T], fallback: T) -> T:
    """call's answer, or fallback when it raises. Murmur removes an authenticator that fails a call, and every
    login then needs the server password, which nobody is given."""
    try:
        return call()
    except Exception:
        LOGGER.exception("A check for Murmur failed, so it is answered %r", fallback)
        return fallback


def properties(ice: ModuleType) -> Any:
    """The secret goes with every call, and messages may be as large as Murmur makes them"""
    props = ice.createProperties()
    props.setProperty("Ice.ImplicitContext", "Shared")
    props.setProperty("Ice.MessageSizeMax", str(ICE_MESSAGE_KIB))
    props.setProperty(f"{ADAPTER}.MessageSizeMax", str(ADAPTER_MESSAGE_KIB))
    return props


def servant(mumble: ModuleType, auth: Authenticator) -> Any:
    """A ServerAuthenticator that delegates to the Ice-free Authenticator"""

    class IceAuthenticator(mumble.ServerAuthenticator):  # type: ignore[misc,name-defined]
        """Murmur calls these for every login"""

        def authenticate(
            self,
            name: str,
            pw: str,
            certificates: list[bytes],
            certhash: str,
            certstrong: bool,
            current: Any = None,
        ) -> tuple[int, str, list[str]]:
            # The password is a credential only from the voice gateway, where it is a mumblermapi ticket. certstrong
            # is Murmur's notion of trust, not ours.
            del certhash, certstrong, current
            user_id = _answer(lambda: auth.authenticate(name, [bytes(cert) for cert in certificates], pw), TRY_LATER)
            return user_id, "", []

        def getInfo(self, id: int, current: Any = None) -> tuple[bool, dict[Any, str]]:
            del current
            name = _answer(lambda: auth.id_to_name(id), "")
            return (True, {mumble.UserInfo.UserName: name}) if name else (False, {})

        def nameToId(self, name: str, current: Any = None) -> int:
            del current
            return _answer(lambda: auth.name_to_id(name), UNKNOWN)

        def idToName(self, id: int, current: Any = None) -> str:
            del current
            return _answer(lambda: auth.id_to_name(id), "")

        def idToTexture(self, id: int, current: Any = None) -> bytes:
            del id, current
            return b""

    return IceAuthenticator()


class IceChannels:
    """The reconciler's view of a Murmur virtual server"""

    def __init__(self, server: Any, mumble: ModuleType) -> None:
        self._server = server
        self._mumble = mumble

    def channels(self) -> list[ExistingChannel]:
        """Every channel on the server"""
        return [
            ExistingChannel(c.id, c.parent, c.name, c.temporary, c.description, tuple(c.links))
            for c in self._server.getChannels().values()
        ]

    def add_channel(self, name: str, parent: int, description: str) -> int:
        """Create a channel, with its description. Only Murmur's nesting limit is a refusal: any other error
        means Murmur cannot be worked with, and ends the pass."""
        try:
            channel_id: int = self._server.addChannel(name, parent)
        except self._mumble.NestingLimitException as exc:
            raise ChannelRefused(f"{name!r} would nest past Murmur's channel nesting limit") from exc
        if description:
            state = self._server.getChannelState(channel_id)
            state.description = description
            self._server.setChannelState(state)
        return channel_id

    def set_description(self, channel_id: int, description: str) -> None:
        """Change a channel's description"""
        state = self._server.getChannelState(channel_id)
        state.description = description
        self._server.setChannelState(state)

    def remove_channel(self, channel_id: int) -> None:
        """Remove a channel; Murmur moves its users to the parent. One already gone, such as a temporary channel that
        emptied meanwhile, counts as removed."""
        with may_be_gone(self._mumble):
            self._server.removeChannel(channel_id)


@contextmanager
def may_be_gone(mumble: ModuleType, *also: type[Exception]) -> Iterator[None]:
    """Murmur's errors for a user or channel that went meanwhile, and also, count as done"""
    try:
        yield
    except (mumble.InvalidSessionException, mumble.InvalidChannelException, *also):
        pass  # the user left, or the temporary channel emptied, meanwhile


def virtual_server(meta: Any, server_id: int | None) -> Any:
    """The configured virtual server, or the only one running"""
    if server_id is not None:
        server = meta.getServer(server_id)
        if server is None:
            raise RuntimeError(f"Murmur has no virtual server {server_id}")
        return server
    booted = meta.getBootedServers()
    if len(booted) != 1:
        raise RuntimeError(f"expected one running virtual server, Murmur has {len(booted)}")
    return booted[0]
