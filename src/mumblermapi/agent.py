"""murmur-agent: the Ice glue between Murmur and the authentication and channel logic.

Ice comes from the container image (Ubuntu's python3-zeroc-ice, the same Ice 3.7 that Murmur links), so this
module imports it lazily. The glue is unit-tested against a fake Murmur; loading Ice and the run loop need
the real one.
"""

