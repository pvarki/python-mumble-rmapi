LOGGER = logging.getLogger(__name__)
_SLICE_FALLBACK_DIR = "/usr/share/ice/slice"
# Murmur forwards a login's name and password, before checking either, from a message of up to 8 MiB. It decodes
# them as UTF-8 and encodes them again for Ice, which makes each invalid byte three, and it drops the authenticator
# when the call fails. Anything smaller on the agent's adapter lets anyone stop every login; the certificate chain
# needs room on top.
MURMUR_MESSAGE_BYTES = 0x7FFFFF
ADAPTER = "Agent"
ADAPTER_MESSAGE_KIB = 3 * MURMUR_MESSAGE_BYTES // 1024 + 1024
# Murmur's answers list every user or channel at once and have no such bound: comments stay under 5000 characters
# with HTML off, so this holds several hundred users' worth, but nothing in Murmur caps the plugin data a client
# sends.
ICE_MESSAGE_KIB = 10 * 1024


def _load_ice() -> tuple[ModuleType, ModuleType]:  # pragma: no cover  # needs the image's Ice
    import Ice  # provided by the container image

    slice_dir = Ice.getSliceDir() or _SLICE_FALLBACK_DIR
    Ice.loadSlice("", ["-I" + slice_dir, str(files("mumblermapi") / "MumbleServer.ice")])
    import MumbleServer  # generated by loadSlice above

    return Ice, MumbleServer


def _answer[T](call: Callable[[], T], fallback: T) -> T:
    """call's answer, or fallback when it raises. Murmur removes an authenticator that fails a call, and every
    login then needs the server password, which nobody is given."""
    try:
        return call()
    except Exception:
        LOGGER.exception("A check for Murmur failed, so it is answered %r", fallback)
        return fallback


def _properties(ice: ModuleType) -> Any:
    """The secret goes with every call, and messages may be as large as Murmur makes them"""
    properties = ice.createProperties()
    properties.setProperty("Ice.ImplicitContext", "Shared")
    properties.setProperty("Ice.MessageSizeMax", str(ICE_MESSAGE_KIB))
    properties.setProperty(f"{ADAPTER}.MessageSizeMax", str(ADAPTER_MESSAGE_KIB))
    return properties


def _servant(mumble: ModuleType, auth: Authenticator) -> Any:
    """A ServerAuthenticator that delegates to the Ice-free Authenticator"""

    class IceAuthenticator(mumble.ServerAuthenticator):  # type: ignore[misc,name-defined]
        """Murmur calls these for every login"""

        def authenticate(
            self,
            name: str,
            pw: str,
            certificates: list[bytes],
            certhash: str,
            certstrong: bool,
            current: Any = None,
        ) -> tuple[int, str, list[str]]:
            # The password is a credential only from the voice gateway, where it is a mumblermapi ticket. certstrong
            # is Murmur's notion of trust, not ours.
            del certhash, certstrong, current
            user_id = _answer(lambda: auth.authenticate(name, [bytes(cert) for cert in certificates], pw), TRY_LATER)
            return user_id, "", []

        def getInfo(self, id: int, current: Any = None) -> tuple[bool, dict[Any, str]]:
            del current
            name = _answer(lambda: auth.id_to_name(id), "")
            return (True, {mumble.UserInfo.UserName: name}) if name else (False, {})

        def nameToId(self, name: str, current: Any = None) -> int:
            del current
            return _answer(lambda: auth.name_to_id(name), UNKNOWN)

        def idToName(self, id: int, current: Any = None) -> str:
            del current
            return _answer(lambda: auth.id_to_name(id), "")

        def idToTexture(self, id: int, current: Any = None) -> bytes:
            del id, current
            return b""

    return IceAuthenticator()


class IceChannels:
    """The reconciler's view of a Murmur virtual server"""

    def __init__(self, server: Any, mumble: ModuleType) -> None:
        self._server = server
        self._mumble = mumble

    def channels(self) -> list[ExistingChannel]:
        """Every channel on the server"""
        return [
            ExistingChannel(c.id, c.parent, c.name, c.temporary, c.description, tuple(c.links))
            for c in self._server.getChannels().values()
        ]

    def add_channel(self, name: str, parent: int, description: str) -> int:
        """Create a channel, with its description. Only Murmur's nesting limit is a refusal: any other error
        means Murmur cannot be worked with, and ends the pass."""
        try:
            channel_id: int = self._server.addChannel(name, parent)
        except self._mumble.NestingLimitException as exc:
            raise ChannelRefused(f"{name!r} would nest past Murmur's channel nesting limit") from exc
        if description:
            state = self._server.getChannelState(channel_id)
            state.description = description
            self._server.setChannelState(state)
        return channel_id

    def set_description(self, channel_id: int, description: str) -> None:
        """Change a channel's description"""
        state = self._server.getChannelState(channel_id)
        state.description = description
        self._server.setChannelState(state)

    def remove_channel(self, channel_id: int) -> None:
        """Remove a channel; Murmur moves its users to the parent. One already gone, such as a temporary channel that
        emptied meanwhile, counts as removed."""
        with _may_be_gone(self._mumble):
            self._server.removeChannel(channel_id)


def _sweep(mumble: ModuleType, server: Any, auth: Authenticator) -> None:
    """Disconnect users whose certificate no longer passes, such as after a revocation"""
    for session, user in server.getUsers().items():
        try:
            chain = [bytes(cert) for cert in server.getCertificateList(session)]
        except mumble.InvalidSessionException:
            continue  # left meanwhile
        refusal = auth.refusal(user.name, chain)
        if refusal is not None and not refusal.transient:
            with _may_be_gone(mumble):
                LOGGER.warning("Disconnecting %r: %s", user.name, refusal.reason)
                server.kickUser(session, refusal.reason)


def _set_acl(mumble: ModuleType, server: Any, channel_id: int, acl: Acl) -> None:
    inherit, rules, groups = acl
    server.setACL(
        channel_id,
        [mumble.ACL(here, subs, False, user, group, allow, deny) for here, subs, user, group, allow, deny in rules],
        [
            mumble.Group(name, False, inh, inheritable, list(add), list(rem), [])
            for name, inh, inheritable, add, rem in groups
        ],
        inherit,
    )


def _sessions(server: Any) -> list[Session]:
    return [Session(session, user.name, user.channel) for session, user in server.getUsers().items()]


def _enforce(ice: ModuleType, mumble: ModuleType, server: Any, policy: Policy, ids: UserIds, units: bool) -> list[str]:
    """Make Murmur match the policy, and return the paths of nets Murmur refused to create. Until the policy is
    known, Units/ and Missions/ are left as they are.

    Refused callsigns go first, so that nothing later in the pass can hold their disconnection up. A net Murmur
    refuses is left out with the nets under it, as if it were not created yet, and the other nets go on.
    """
    sessions = _sessions(server)
    kicked = refused(policy, sessions)
    for session in kicked:
        with _may_be_gone(mumble):
            LOGGER.warning("Disconnecting session %d: refused by mumblermapi", session)
            server.kickUser(session, "revoked or voice disabled in Deploy App")

    channels = IceChannels(server, mumble)
    desired = desired_tree(policy.specs(), policy.mission_specs()) if units else desired_tree(())
    created, left_out = reconcile(channels, desired)
    if created:
        LOGGER.info("Created channels: %s", ", ".join(created))
    if not units:
        return left_out
    existing = channels.channels()
    roots = {c.name: c.id for c in existing if c.parent == 0}
    removed = prune(channels, policy.specs(), roots["Units"], "/Units")
    removed += prune(channels, policy.mission_specs(), roots["Missions"], "/Missions")
    if removed:
        LOGGER.info("Removed channels: %s", ", ".join(removed))
        existing = channels.channels()
    names = ids.names()
    access = combine(
        plan(policy.units, existing, roots["Units"], names),
        plan(policy.missions, existing, roots["Missions"], names),
    )
    for channel_id, acl in access.acls.items():
        with _may_be_gone(mumble):
            try:
                current: Acl | None = acl_of(*server.getACL(channel_id))
            except ice.MemoryLimitException:
                # Rules too large to read, such as a member's own in their temporary channel: ours replace them
                current = None
            if current != acl:
                _set_acl(mumble, server, channel_id, acl)
                LOGGER.info("Set access rules of channel %d", channel_id)
    # A link carries a restricted net's audio to whoever is in the other channel, and one made while its maker
    # still had access outlives the access. Restricted nets are never linked.
    for channel in existing:
        if channel.links and channel.id in access.admitted:
            with _may_be_gone(mumble):
                state = server.getChannelState(channel.id)
                LOGGER.info("Unlinking channel %d from %s", channel.id, state.links)
                state.links = []
                server.setChannelState(state)

    # Read again: anyone who entered a net before its rules were written is still inside, and reconcile may
    # have moved people
    remaining = [s for s in _sessions(server) if s.session not in kicked]
    # Murmur's slice declares no exceptions for the listener calls, so Ice reports a session or channel that is
    # gone as an unknown one
    listeners = {}
    for channel_id in access.admitted:
        with _may_be_gone(mumble, ice.UnknownUserException):
            listeners[channel_id] = server.getListeningUsers(channel_id)
    actions = violations(access, remaining, listeners, shadows(existing, roots["Missions"]))
    for session, target in actions.move:
        with _may_be_gone(mumble):
            state = server.getState(session)
            LOGGER.info("Moving %r from channel %d to %d", state.name, state.channel, target)
            state.channel = target
            server.setState(state)
    for session, channel_id in actions.unlisten:
        with _may_be_gone(mumble, ice.UnknownUserException):
            LOGGER.info("Stopping session %d listening to channel %d", session, channel_id)
            server.stopListening(session, channel_id)
    return left_out


def _warn_left_out(left_out: list[str], before: list[str]) -> list[str]:
    """Warn about the nets Murmur refuses when they change, not every round; returns them for the next round"""
    if left_out and set(left_out) != set(before):
        LOGGER.warning(
            "Murmur refused these nets, so they and the nets under them are left out: %s", ", ".join(left_out)
        )
    return left_out


def _presence(mumble: ModuleType, server: Any) -> list[Entry]:
    """Who is connected, and in which net"""
    return presence(_sessions(server), channel_paths(IceChannels(server, mumble).channels()))


@contextmanager
def _may_be_gone(mumble: ModuleType, *also: type[Exception]) -> Iterator[None]:
    try:
        yield
    except (mumble.InvalidSessionException, mumble.InvalidChannelException, *also):
        pass  # the user left, or the temporary channel emptied, meanwhile


def _server(meta: Any, server_id: int | None) -> Any:
    """The configured virtual server, or the only one running"""
    if server_id is not None:
        server = meta.getServer(server_id)
        if server is None:
            raise RuntimeError(f"Murmur has no virtual server {server_id}")
        return server
    booted = meta.getBootedServers()
    if len(booted) != 1:
        raise RuntimeError(f"expected one running virtual server, Murmur has {len(booted)}")
    return booted[0]


@dataclass
class Rounds:
    """What murmur-agent does with Murmur each round, and what it carries from one round to the next"""

    ice: ModuleType
    mumble: ModuleType
    auth: Authenticator
    ids: UserIds
    reporter: PresenceReporter | None
    sweep_seconds: float
    next_sweep: float = field(default=0.0, init=False)
    left_out: list[str] = field(default_factory=list, init=False)

    def round(self, server: Any, policy: Policy, units: bool) -> None:
        """Sweep certificates when due, then make Murmur match the policy and report presence.

        The sweep goes first, on its own, so that no lasting failure to enforce the policy stops disconnecting
        revoked certificates. Presence follows enforcement, so a pass that keeps failing stops the reports and
        mumblermapi's health shows it. No error ends the agent: Murmur's authenticator, and so every login, would
        go with it.
        """
        not_ready = (self.ice.Exception, RuntimeError)
        if time.monotonic() >= self.next_sweep:
            try:
                _sweep(self.mumble, server, self.auth)
            except not_ready as exc:
                self._failed("the certificate sweep", exc)
            except Exception:
                LOGGER.exception("Unexpected error in the certificate sweep")
            else:
                self.next_sweep = time.monotonic() + self.sweep_seconds
        try:
            left_out = _enforce(self.ice, self.mumble, server, policy, self.ids, units)
            if self.reporter:
                self.reporter.report(_presence(self.mumble, server), time.monotonic())
        except not_ready as exc:
            self._failed("the plan", exc)
        except Exception:
            LOGGER.exception("Unexpected error in the plan")
        else:
            self.left_out = _warn_left_out(left_out, self.left_out)

    def _failed(self, what: str, exc: Exception) -> None:
        if isinstance(exc, self.ice.MemoryLimitException):
            LOGGER.error("Murmur's answer for %s is over the agent's %d KiB limit: %s", what, ICE_MESSAGE_KIB, exc)
        else:
            LOGGER.warning("Murmur not ready for %s: %s", what, exc)


def run(config: AgentConfig, stop: threading.Event) -> None:  # pragma: no cover  # needs Ice and Murmur
    """Register with Murmur and keep it in shape until stopped"""
    ice, mumble = _load_ice()
    config.data_dir.mkdir(parents=True, exist_ok=True)
    ids = UserIds(config.data_dir / "user-ids.json")
    # With mumblermapi, its store is the plan; without it, the channels file is.
    source = PolicySource(config.state_url, Policy()) if config.state_url else None
    fixed = None if source else from_plan(load_plan(config.channels_file))

    def policy() -> Policy:
        return source.policy if source else fixed or Policy()

    reporter = PresenceReporter(config.presence_url) if config.presence_url else None

    auth = Authenticator(
        CertVerifier.from_pem_file(config.ca_bundle),
        OcspChecker(url_override=config.ocsp_url, cache_seconds=config.ocsp_cache_seconds),
        ids,
        policy=policy,
        gateway=CertVerifier.from_pem_file(config.gateway_ca) if config.gateway_ca else None,
    )

    init_data = ice.InitializationData()
    init_data.properties = _properties(ice)
    with ice.initialize(init_data) as communicator:
        communicator.getImplicitContext().put("secret", config.ice_secret)
        adapter = communicator.createObjectAdapterWithEndpoints(ADAPTER, f"tcp -h 127.0.0.1 -p {config.callback_port}")
        adapter.activate()
        authenticator = mumble.ServerAuthenticatorPrx.uncheckedCast(adapter.addWithUUID(_servant(mumble, auth)))
        meta = mumble.MetaPrx.uncheckedCast(
            communicator.stringToProxy(f"Meta:tcp -h {config.ice_host} -p {config.ice_port}")
        )
        rounds = Rounds(ice, mumble, auth, ids, reporter, config.sweep_seconds)
        while not stop.is_set():
            if source:
                source.refresh()
            try:
                server = _server(meta, config.server_id)
                # Re-registering every round re-attaches the authenticator after a Murmur restart.
                server.setAuthenticator(authenticator)
            except (ice.Exception, RuntimeError) as exc:
                LOGGER.warning("Murmur not ready: %s", exc)
            else:
                rounds.round(server, policy(), units=source is None or source.ready)
            stop.wait(config.poll_seconds)


def main() -> None:  # pragma: no cover  # the container entrypoint
    """murmur-agent entrypoint"""
    add_trace_and_audit()
    init_logging(logging.INFO)
    config = AgentConfig.from_env()
    stop = threading.Event()
    for signum in (signal.SIGTERM, signal.SIGINT):
        signal.signal(signum, lambda *_: stop.set())
    LOGGER.info("murmur-agent starting for Murmur at %s:%d", config.ice_host, config.ice_port)
    run(config, stop)
