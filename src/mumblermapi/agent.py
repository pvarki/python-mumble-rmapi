LOGGER = logging.getLogger(__name__)
_SLICE_FALLBACK_DIR = "/usr/share/ice/slice"


def _load_ice() -> tuple[ModuleType, ModuleType]:  # pragma: no cover  # needs the image's Ice
    import Ice  # provided by the container image

    slice_dir = Ice.getSliceDir() or _SLICE_FALLBACK_DIR
    Ice.loadSlice("", ["-I" + slice_dir, str(files("mumblermapi") / "MumbleServer.ice")])
    import MumbleServer  # generated by loadSlice above

    return Ice, MumbleServer


def _servant(mumble: ModuleType, auth: Authenticator) -> Any:
    """A ServerAuthenticator that delegates to the Ice-free Authenticator"""

    class IceAuthenticator(mumble.ServerAuthenticator):  # type: ignore[misc,name-defined]
        """Murmur calls these for every login"""

        def authenticate(
            self,
            name: str,
            pw: str,
            certificates: list[bytes],
            certhash: str,
            certstrong: bool,
            current: Any = None,
        ) -> tuple[int, str, list[str]]:
            # Passwords are not credentials here, and certstrong is Murmur's notion of trust, not ours.
            del pw, certhash, certstrong, current
            return auth.authenticate(name, [bytes(cert) for cert in certificates]), "", []

        def getInfo(self, id: int, current: Any = None) -> tuple[bool, dict[Any, str]]:
            del current
            name = auth.id_to_name(id)
            return (True, {mumble.UserInfo.UserName: name}) if name else (False, {})

        def nameToId(self, name: str, current: Any = None) -> int:
            del current
            return auth.name_to_id(name)

        def idToName(self, id: int, current: Any = None) -> str:
            del current
            return auth.id_to_name(id)

        def idToTexture(self, id: int, current: Any = None) -> bytes:
            del id, current
            return b""

    return IceAuthenticator()


class IceChannels:
    """The reconciler's view of a Murmur virtual server"""

    def __init__(self, server: Any) -> None:
        self._server = server

    def channels(self) -> list[ExistingChannel]:
        """Every channel on the server"""
        return [
            ExistingChannel(c.id, c.parent, c.name, c.temporary, c.description, tuple(c.links))
            for c in self._server.getChannels().values()
        ]

    def add_channel(self, name: str, parent: int, description: str) -> int:
        """Create a channel, with its description"""
        channel_id: int = self._server.addChannel(name, parent)
        if description:
            state = self._server.getChannelState(channel_id)
            state.description = description
            self._server.setChannelState(state)
        return channel_id

    def set_description(self, channel_id: int, description: str) -> None:
        """Change a channel's description"""
        state = self._server.getChannelState(channel_id)
        state.description = description
        self._server.setChannelState(state)

    def remove_channel(self, channel_id: int) -> None:
        """Remove a channel; Murmur moves its users to the parent"""
        self._server.removeChannel(channel_id)


def _sweep(mumble: ModuleType, server: Any, auth: Authenticator) -> None:
    """Disconnect users whose certificate no longer passes, such as after a revocation"""
    for session, user in server.getUsers().items():
        try:
            chain = [bytes(cert) for cert in server.getCertificateList(session)]
        except mumble.InvalidSessionException:
            continue  # left meanwhile
        refusal = auth.refusal(user.name, chain)
        if refusal is not None and not refusal.transient:
            with _may_be_gone(mumble):
                LOGGER.warning("Disconnecting %r: %s", user.name, refusal.reason)
                server.kickUser(session, refusal.reason)


def _set_acl(mumble: ModuleType, server: Any, channel_id: int, acl: Acl) -> None:
    inherit, rules, groups = acl
    server.setACL(
        channel_id,
        [mumble.ACL(here, subs, False, user, group, allow, deny) for here, subs, user, group, allow, deny in rules],
        [
            mumble.Group(name, False, inh, inheritable, list(add), list(rem), [])
            for name, inh, inheritable, add, rem in groups
        ],
        inherit,
    )


def _sessions(server: Any) -> list[Session]:
    return [Session(session, user.name, user.channel) for session, user in server.getUsers().items()]


def _enforce(mumble: ModuleType, server: Any, policy: Policy, ids: UserIds, units: bool) -> None:
    """Make Murmur match the policy. Until the policy is known, Units/ and Missions/ are left as they are.

    Refused callsigns go first, so that nothing later in the pass can hold their disconnection up.
    """
    sessions = _sessions(server)
    kicked = refused(policy, sessions)
    for session in kicked:
        with _may_be_gone(mumble):
            LOGGER.warning("Disconnecting session %d: refused by mumblermapi", session)
            server.kickUser(session, "revoked or voice disabled in Deploy App")

    channels = IceChannels(server)
    created = reconcile(channels, desired_tree(policy.specs(), policy.mission_specs()) if units else desired_tree(()))
    if created:
        LOGGER.info("Created channels: %s", ", ".join(created))
    if not units:
        return
    existing = channels.channels()
    roots = {c.name: c.id for c in existing if c.parent == 0}
    removed = prune(channels, policy.specs(), roots["Units"], "/Units")
    removed += prune(channels, policy.mission_specs(), roots["Missions"], "/Missions")
    if removed:
        LOGGER.info("Removed channels: %s", ", ".join(removed))
        existing = channels.channels()
    names = ids.names()
    access = combine(
        plan(policy.units, existing, roots["Units"], names),
        plan(policy.missions, existing, roots["Missions"], names),
    )
    for channel_id, acl in access.acls.items():
        with _may_be_gone(mumble):
            if acl_of(*server.getACL(channel_id)) != acl:
                _set_acl(mumble, server, channel_id, acl)
                LOGGER.info("Set access rules of channel %d", channel_id)
    # A link carries a restricted net's audio to whoever is in the other channel, and one made while its maker
    # still had access outlives the access. Restricted nets are never linked.
    for channel in existing:
        if channel.links and channel.id in access.admitted:
            with _may_be_gone(mumble):
                state = server.getChannelState(channel.id)
                LOGGER.info("Unlinking channel %d from %s", channel.id, state.links)
                state.links = []
                server.setChannelState(state)

    # Read again: anyone who entered a net before its rules were written is still inside, and reconcile may
    # have moved people
    remaining = [s for s in _sessions(server) if s.session not in kicked]
    listeners = {}
    for channel_id in access.admitted:
        with _may_be_gone(mumble):
            listeners[channel_id] = server.getListeningUsers(channel_id)
    actions = violations(access, remaining, listeners, shadows(existing, roots["Missions"]))
    for session, target in actions.move:
        with _may_be_gone(mumble):
            state = server.getState(session)
            LOGGER.info("Moving %r from channel %d to %d", state.name, state.channel, target)
            state.channel = target
            server.setState(state)
    for session, channel_id in actions.unlisten:
        with _may_be_gone(mumble):
            LOGGER.info("Stopping session %d listening to channel %d", session, channel_id)
            server.stopListening(session, channel_id)


def _presence(server: Any) -> list[Entry]:
    """Who is connected, and in which net"""
    return presence(_sessions(server), channel_paths(IceChannels(server).channels()))


@contextmanager
def _may_be_gone(mumble: ModuleType) -> Iterator[None]:
    try:
        yield
    except (mumble.InvalidSessionException, mumble.InvalidChannelException):
        pass  # the user left, or the temporary channel emptied, meanwhile


def _server(meta: Any, server_id: int | None) -> Any:
    """The configured virtual server, or the only one running"""
    if server_id is not None:
        server = meta.getServer(server_id)
        if server is None:
            raise RuntimeError(f"Murmur has no virtual server {server_id}")
        return server
    booted = meta.getBootedServers()
    if len(booted) != 1:
        raise RuntimeError(f"expected one running virtual server, Murmur has {len(booted)}")
    return booted[0]


def run(config: AgentConfig, stop: threading.Event) -> None:  # pragma: no cover  # needs Ice and Murmur
    """Register with Murmur and keep it in shape until stopped"""
    ice, mumble = _load_ice()
    config.data_dir.mkdir(parents=True, exist_ok=True)
    ids = UserIds(config.data_dir / "user-ids.json")
    # With mumblermapi, its store is the plan; without it, the channels file is.
    source = PolicySource(config.state_url, Policy()) if config.state_url else None
    fixed = None if source else from_plan(load_plan(config.channels_file))

    def policy() -> Policy:
        return source.policy if source else fixed or Policy()

    reporter = PresenceReporter(config.presence_url) if config.presence_url else None

    auth = Authenticator(
        CertVerifier.from_pem_file(config.ca_bundle),
        OcspChecker(url_override=config.ocsp_url, cache_seconds=config.ocsp_cache_seconds),
        ids,
        policy=policy,
    )

    properties = ice.createProperties()
    properties.setProperty("Ice.ImplicitContext", "Shared")
    init_data = ice.InitializationData()
    init_data.properties = properties
    with ice.initialize(init_data) as communicator:
        communicator.getImplicitContext().put("secret", config.ice_secret)
        adapter = communicator.createObjectAdapterWithEndpoints("Agent", f"tcp -h 127.0.0.1 -p {config.callback_port}")
        adapter.activate()
        authenticator = mumble.ServerAuthenticatorPrx.uncheckedCast(adapter.addWithUUID(_servant(mumble, auth)))
        meta = mumble.MetaPrx.uncheckedCast(
            communicator.stringToProxy(f"Meta:tcp -h {config.ice_host} -p {config.ice_port}")
        )
        next_sweep = 0.0
        while not stop.is_set():
            if source:
                source.refresh()
            try:
                server = _server(meta, config.server_id)
                # Re-registering every round re-attaches the authenticator after a Murmur restart.
                server.setAuthenticator(authenticator)
                _enforce(mumble, server, policy(), ids, units=source is None or source.ready)
                if reporter:
                    reporter.report(_presence(server), time.monotonic())
                if time.monotonic() >= next_sweep:
                    _sweep(mumble, server, auth)
                    next_sweep = time.monotonic() + config.sweep_seconds
            except (ice.Exception, RuntimeError) as exc:
                LOGGER.warning("Murmur not ready: %s", exc)
            stop.wait(config.poll_seconds)


def main() -> None:  # pragma: no cover  # the container entrypoint
    """murmur-agent entrypoint"""
    init_logging(logging.INFO)
    config = AgentConfig.from_env()
    stop = threading.Event()
    for signum in (signal.SIGTERM, signal.SIGINT):
        signal.signal(signum, lambda *_: stop.set())
    LOGGER.info("murmur-agent starting for Murmur at %s:%d", config.ice_host, config.ice_port)
    run(config, stop)
